// Audit S-04: cap message payload size server-side.
const MAX_CONTENT_LENGTH = 8192;

type MessageCreateData = Omit<Message, 'id' | 'timestamp' | 'reactions' | 'attachments' | 'isEdited'>;

/** A keyed create: its key and this dispatch's attempt (Phase 5 T2). */
interface KeyedCreate {
  clientMessageId: string;
  attempt: MessageAttempt;
}

/**
 * Phase 4 FR-024: optional composition key generated by the drawer composer
 * and resent on every retry of the same composition. Absent (the published
 * app) → legacy create; present → at most one message per key, sender, and
 * conversation.
 */
function parseClientMessageId(value: unknown): { ok: true; value: string | undefined } | { ok: false } {
  if (value === undefined || value === null) {
    return { ok: true, value: undefined };
  }
  if (!isUuid(value)) {
    return { ok: false };
  }
  return { ok: true, value: value.toLowerCase() };
}

const TOO_MANY_ATTACHMENTS_MESSAGE = `A message can carry at most ${MAX_ATTACHMENTS_PER_MESSAGE} attachments`;

/**
 * Phase 4 T12 (FR-008): optional ids of the caller's pending uploads
 * (POST /api/messages/upload) to attach. Absent or empty → no attachments.
 */
function parseAttachmentIds(
  value: unknown
): { ok: true; value: string[] | undefined } | { ok: false; code: string; message: string } {
  if (value === undefined || value === null) {
    return { ok: true, value: undefined };
  }
  if (!Array.isArray(value) || value.some((id) => !isUuid(id))) {
    return { ok: false, code: 'INVALID_ATTACHMENT_ID', message: 'attachmentIds must be an array of upload ids' };
  }
  const ids = (value as string[]).map((id) => id.toLowerCase());
  if (ids.length === 0) {
    return { ok: true, value: undefined };
  }
  if (ids.length > MAX_ATTACHMENTS_PER_MESSAGE) {
    return { ok: false, code: 'TOO_MANY_ATTACHMENTS', message: TOO_MANY_ATTACHMENTS_MESSAGE };
  }
  if (new Set(ids).size !== ids.length) {
    return { ok: false, code: 'DUPLICATE_ATTACHMENT', message: 'attachmentIds must not repeat an upload' };
  }
  return { ok: true, value: ids };
}

/**
 * A replayed key must carry the same composition: content, reply target, the
 * same attachment set (attachment id = upload id), and — for messages without
 * attachments — the same type (attachment messages derive their type from
 * their attachments). Phase 5 T2 (FR-024): compared against the ORIGINAL
 * submitted composition recorded with the key; keyed messages created before
 * Phase 5 have none and are compared against the stored message (Phase 4).
 * Phase 5 T4: the requested mention ids are part of the composition (a stored
 * composition without them requested none); a message without a recorded
 * composition predates mentions, so only a replay requesting none matches.
 */
function isSameComposition(
  storedComposition: MessageComposition | null | undefined,
  stored: Message,
  storedAttachmentIdList: readonly string[],
  requested: MessageComposition
): boolean {
  if (storedComposition) {
    return isSameStoredComposition(storedComposition, requested);
  }
  const storedAttachmentIds = [...storedAttachmentIdList].sort();
  const expectedAttachmentIds = [...requested.attachmentIds].sort();
  return (
    requested.mentionIds.length === 0 &&
    stored.content === requested.content &&
    (requested.type === null || stored.type === requested.type) &&
    (stored.replyToId ?? null) === requested.replyToId &&
    storedAttachmentIds.length === expectedAttachmentIds.length &&
    storedAttachmentIds.every((id, index) => id === expectedAttachmentIds[index])
  );
}

// Responses carry the message, its attachments and reactions — not other
// users' pins or stars, which findById (service client) also loads. Keyed
// responses carry the key (FR-034) on the message and at the top level, plus
// the attempt generation they answer.
function messageResponse(message: Message, status: 200 | 201, keyed?: KeyedCreate): NextResponse {
  const responseMessage: Message = { ...message, pins: undefined, stars: undefined };
  if (!keyed) {
    return NextResponse.json({ message: responseMessage }, { status });
  }
  return NextResponse.json(
    {
      message: { ...responseMessage, clientMessageId: keyed.clientMessageId },
      clientMessageId: keyed.clientMessageId,
      ...(keyed.attempt.generation !== undefined ? { attemptGeneration: keyed.attempt.generation } : {}),
    },
    { status }
  );
}

function clientKeyReused() {
  return jsonError(409, 'CLIENT_MESSAGE_ID_REUSED', 'clientMessageId was already used for a different message');
}

function attachmentNotFound() {
  return jsonError(400, 'ATTACHMENT_NOT_FOUND', 'An attachment was not found; upload it again');
}

function invalidReplyTarget() {
  return jsonError(400, 'INVALID_REPLY_TARGET', 'replyToId must reference a message in the same conversation');
}

function notParticipant() {
  return jsonError(403, 'NOT_PARTICIPANT', 'You are not a participant of this conversation');
}

function attachmentLinkFailure(error: AttachmentLinkError) {
  switch (error.code) {
    case 'NOT_PARTICIPANT':
      return notParticipant();
    case 'ATTACHMENT_COUNT_INVALID':
      return jsonError(400, 'TOO_MANY_ATTACHMENTS', TOO_MANY_ATTACHMENTS_MESSAGE);
    case 'ATTACHMENT_DUPLICATE':
      return jsonError(400, 'DUPLICATE_ATTACHMENT', 'attachmentIds must not repeat an upload');
    case 'ATTACHMENT_UPLOAD_NOT_FOUND':
      return attachmentNotFound();
    case 'INVALID_REPLY_TARGET':
      return invalidReplyTarget();
    case 'VOICE_NOTE_NOT_ALONE':
      return voiceNoteNotAlone();
  }
}

function voiceNoteNotAlone() {
  return jsonError(400, 'VOICE_NOTE_NOT_ALONE', 'A voice note must be the only attachment of its message');
}

/**
 * Database refusals of a create (fenced attempt, validation race, explicit
 * membership refusal, insertion quota) as BR-005 / FR-008 outcomes; null
 * otherwise — grant and other infrastructure failures answer 500 (recoverable).
 */
function createRefusal(error: unknown): NextResponse | null {
  if (error instanceof InsertionRateLimitError) {
    return error.reason === 'exceeded' ? rateLimitExceededResponse() : rateLimitUnavailableResponse();
  }
  if (error instanceof AttemptSupersededError) {
    return attemptSupersededResponse();
  }
  if (error instanceof MessageDeletedError) {
    return messageDeletedResponse();
  }
  if (error instanceof AttachmentLinkError) {
    return attachmentLinkFailure(error);
  }
  if (error instanceof NotParticipantError) {
    return notParticipant();
  }
  return null;
}

/**
 * Creates the message and links its pending uploads in one transaction
 * (BR-007: never visible partially attached). The uploads must belong to the
 * caller for this conversation and pass the attachment policy on their STORED
 * objects. A keyed create commits only while its attempt is current (Phase 5
 * T2); a fenced one stores and links nothing.
 */
async function createWithAttachments(
  serviceClient: SupabaseClient,
  messageRepository: IMessageRepository,
  conversationRepository: IConversationRepository,
  uploads: IMessageAttachmentUploadRepository,
  messageData: Omit<MessageCreateData, 'type'>,
  attachmentIds: string[],
  keyed: KeyedCreate | undefined
): Promise<NextResponse> {
  const owned = await uploads.findOwned(attachmentIds, messageData.senderId, messageData.conversationId);

  let type = MessageType.FILE;
  const allUploadsPending = owned.length === attachmentIds.length;
  if (allUploadsPending) {
    // Phase 4 T15: a voice note travels alone (the database enforces it too).
    if (owned.length > 1 && owned.some((upload) => upload.duration !== undefined)) {
      return voiceNoteNotAlone();
    }
    const violation = await validateUploadsForLink(serviceClient, owned);
    if (violation) {
      return jsonError(violation.status, violation.code, violation.message);
    }
    type = attachmentMessageType(owned.map((upload) => upload.type));
  } else if (!keyed) {
    // Unknown, another user's, another conversation's, cancelled, or sent.
    return attachmentNotFound();
  }
  // With a key and missing uploads the database decides: a replay of a
  // committed create (its uploads were consumed) or ATTACHMENT_NOT_FOUND.

  let outcome: { messageId: string; created: boolean; storedComposition?: MessageComposition | null };
  try {
    outcome = await uploads.createMessageWithAttachments(
      { ...messageData, type },
      attachmentIds,
      keyed?.clientMessageId,
      keyed?.attempt,
      MESSAGE_INSERTION_QUOTA
    );
  } catch (error) {
    const refusal = createRefusal(error);
    if (refusal) {
      return refusal;
    }
    throw error;
  }

  if (outcome.created && !allUploadsPending) {
    // The database can only replay or refuse when uploads were missing here.
    throw new Error('create_message_attempt linked uploads that failed the policy pre-check');
  }
  if (outcome.created) {
    // Committed: bump activity now so a failed read-back below (500, then a
    // 200 replay on retry) never skips the recipients' badge refresh.
    await touchConversation(conversationRepository, messageData.conversationId);
  }

  const stored = await messageRepository.findById(outcome.messageId);
  if (!stored) {
    throw new Error(`Message ${outcome.messageId} not found after create`);
  }
  // Read strictly: findById degrades attachment read errors to [] (which would
  // turn a genuine replay into a false 409 or answer 201 without files).
  const linkedIds = await uploads.listLinkedAttachmentIds(outcome.messageId);
  if (!outcome.created) {
    // Only a keyed create can replay.
    if (!keyed || !isSameComposition(outcome.storedComposition, stored, linkedIds, keyed.attempt.composition)) {
      return clientKeyReused();
    }
    return messageResponse(stored, 200, keyed);
  }
  if ((stored.attachments ?? []).length !== linkedIds.length) {
    // The message and its files are committed; a retry with the same key
    // replays it (200) once the read succeeds.
    throw new Error(`Attachments of message ${outcome.messageId} could not be read after create`);
  }
  return messageResponse(stored, 201, keyed);
}

// Update conversation last activity. Besides ordering the list, this UPDATE on
// conversations is what fires useConversationRealtime's cache invalidation so
// recipients' unread badges refresh. Unread counts are derived from
// conversation_members.last_read_at (Phase 2.2) — nothing to increment here.
async function touchConversation(conversationRepository: IConversationRepository, conversationId: string) {
  try {
    await conversationRepository.updateLastActivityTimestamp(conversationId);
  } catch (updateError) {
    console.warn('Failed to update conversation activity:', updateError);
    // Don't fail the request if conversation update fails
  }
}

/**
 * POST /api/messages/create
 * Body: { conversationId, content, type?, replyToId?, clientMessageId?,
 *         attachmentIds?, attemptGeneration?, expectedSenderId? }
 * `content` may be empty (or omitted) only when `attachmentIds` lists 1–5 of
 * the caller's pending uploads for this conversation (Phase 4 T12); the type
 * of such a message is derived from its attachments (image or file; a voice
 * note — Phase 4 T15 — is the only attachment of a file message).
 * 201 created; 200 replay of `clientMessageId` (nothing inserted or linked);
 * 409 CLIENT_MESSAGE_ID_REUSED when the replay's composition differs.
 *
 * Phase 5 T2 (FR-006, FR-011, BR-005): `attemptGeneration` (positive integer,
 * requires `clientMessageId` and `expectedSenderId`) makes this dispatch an
 * attempt of its key: it first fences every older generation, and commits only
 * if no newer generation was fenced or dispatched before its commit; otherwise
 * 409 ATTEMPT_SUPERSEDED and nothing is stored. A keyed create without a
 * generation (Phase 4 client) commits only while the key has no fence state.
 * `expectedSenderId` (users.id) different from the authenticated user → 403
 * SENDER_MISMATCH, nothing stored or fenced. A generation-carrying create
 * whose key's committed message was deleted since → 410 MESSAGE_DELETED
 * (nothing stored; the item counts as delivered). A missing conversation answers
 * 403 NOT_PARTICIPANT. Keyed responses carry `clientMessageId` (and
 * `attemptGeneration` when sent).
 *
 * Phase 5 T4 (FR-024, BR-010): `mentionIds` (optional array of at most 50
 * users.id; requires `clientMessageId`; else 400 INVALID_MENTION_IDS) are the
 * requested mentions. They are part of the original composition (a replay
 * requesting a different set → 409 CLIENT_MESSAGE_ID_REUSED; an unchanged
 * replay → 200 even if a mentioned user left since) and, on first creation,
 * the database stores in the same transaction a mention for each one that is
 * a current member other than the sender (others create nothing). Messages in
 * responses carry `mentionedUserIds` (stored mentions, sorted).
 *
 * Phase 5 T3 (FR-008): budgets, each a transient 429 `rate_limited` when
 * exhausted or when it cannot be checked (fail-closed). The request is
 * authenticated first (401, nobody charged); then every authenticated request
 * — malformed or invalid bodies, replays and quota losers included — consumes
 * the request budget before anything else; a generation-carrying create's
 * fence step consumes the fence budget; only a winning insertion consumes the
 * insertion quota (charged by the database in the insertion's transaction,
 * for keyed, unkeyed and attachment creates alike). A grant or other
 * infrastructure failure answers 500; only the database's explicit membership
 * refusal answers 403 NOT_PARTICIPANT.
 */
export async function POST(request: NextRequest) {
  try {
    const auth = await requireAuthUser();
    if ('errorResponse' in auth) {
      return auth.errorResponse;
    }
    const serviceClient = await createSupabaseServerClient('service_role');
    const overRequestBudget = await enforceRateLimit(serviceClient, auth.dbUser.id, 'message:create-request');
    if (overRequestBudget) {
      return overRequestBudget;
    }

    let body: Record<string, unknown>;
    try {
      body = await request.json();
    } catch {
      return jsonError(400, 'BAD_REQUEST', 'Invalid JSON payload');
    }
    if (typeof body !== 'object' || body === null || Array.isArray(body)) {
      return jsonError(400, 'BAD_REQUEST', 'Invalid JSON payload');
    }

    const attachmentIds = parseAttachmentIds(body.attachmentIds);
    if (!attachmentIds.ok) {
      return jsonError(400, attachmentIds.code, attachmentIds.message);
    }
    const hasAttachments = attachmentIds.value !== undefined;

    const conversationId = typeof body.conversationId === 'string' ? body.conversationId : null;
    const rawContent = body.content === undefined && hasAttachments ? '' : body.content;
    if (!conversationId || typeof rawContent !== 'string') {
      return jsonError(400, 'BAD_REQUEST', 'Missing required fields: conversationId, content');
    }
    if (!isUuid(conversationId)) {
      return jsonError(400, 'BAD_REQUEST', 'conversationId must be a UUID');
    }

    const trimmedContent = rawContent.trim();
    if (trimmedContent.length === 0 && !hasAttachments) {
      return jsonError(400, 'BAD_REQUEST', 'Content must not be empty');
    }
    if (trimmedContent.length > MAX_CONTENT_LENGTH) {
      return jsonError(413, 'CONTENT_TOO_LARGE', `Content exceeds the ${MAX_CONTENT_LENGTH} character limit`);
    }

    const clientMessageId = parseClientMessageId(body.clientMessageId);
    if (!clientMessageId.ok) {
      return jsonError(400, 'INVALID_CLIENT_MESSAGE_ID', 'clientMessageId must be a UUID');
    }
    const attemptGeneration = parseAttemptGeneration(body.attemptGeneration, clientMessageId.value !== undefined);
    if (!attemptGeneration.ok) {
      return attemptGeneration.response;
    }
    const expectedSenderId = parseExpectedSenderId(body.expectedSenderId, attemptGeneration.value !== undefined);
    if (!expectedSenderId.ok) {
      return expectedSenderId.response;
    }
    const mentionIds = parseMentionIds(body.mentionIds, clientMessageId.value !== undefined);
    if (!mentionIds.ok) {
      return mentionIds.response;
    }

    const ctx = await authorizeConversationParticipant(auth, serviceClient, conversationId, {
      expectedSenderId: expectedSenderId.value,
      missingConversationAsNotParticipant: true,
    });
    if (isAuthzFailure(ctx)) {
      return ctx.errorResponse;
    }
    const { dbUser, conversation } = ctx;

    const messageRepository: IMessageRepository = new SupabaseMessageRepository(serviceClient);
    const conversationRepository: IConversationRepository = new SupabaseConversationRepository(serviceClient);

    // Audit S-04: replyToId must reference a message in the SAME conversation.
    // Keyed creates are validated by the database AFTER the replay check
    // (create_message_attempt): an unchanged replay of a stored message is not
    // re-validated (FR-024), so a reply target deleted since cannot turn it
    // into a refusal; a new insertion still gets 400 INVALID_REPLY_TARGET.
    let replyToId: string | undefined;
    if (body.replyToId !== undefined && body.replyToId !== null) {
      if (typeof body.replyToId !== 'string') {
        return jsonError(400, 'BAD_REQUEST', 'replyToId must be a string');
      }
      if (!isUuid(body.replyToId)) {
        return invalidReplyTarget();
      }
    }
    if (typeof body.replyToId === 'string' && clientMessageId.value) {
      replyToId = body.replyToId.toLowerCase();
    } else if (typeof body.replyToId === 'string') {
      const { data: replyTarget, error: replyError } = await serviceClient
        .from('messages')
        .select('id, conversation_id')
        .eq('id', body.replyToId)
        .maybeSingle();
      if (replyError) {
        console.error('Failed to validate replyToId:', replyError.message);
        return jsonError(500, 'INTERNAL_ERROR', 'Failed to create message');
      }
      if (!replyTarget || replyTarget.conversation_id !== conversation.id) {
        return invalidReplyTarget();
      }
      replyToId = replyTarget.id;
    }

    const baseMessageData: Omit<MessageCreateData, 'type'> = {
      conversationId: conversation.id,
      senderId: dbUser.id,
      content: trimmedContent,
      // Audit S-04: never trust client-supplied status (pre-marked read/delivered).
      status: MessageStatus.SENT,
      replyToId,
    };

    const safeType: MessageType = Object.values(MessageType).includes(body.type as MessageType)
      ? (body.type as MessageType)
      : MessageType.TEXT;

    let keyed: KeyedCreate | undefined;
    if (clientMessageId.value) {
      keyed = {
        clientMessageId: clientMessageId.value,
        attempt: {
          generation: attemptGeneration.value,
          composition: buildComposition({
            content: trimmedContent,
            type: attachmentIds.value ? null : safeType,
            replyToId,
            attachmentIds: attachmentIds.value ?? [],
            mentionIds: mentionIds.value,
          }),
        },
      };
    }

    if (keyed?.attempt.generation !== undefined) {
      // FR-006: an attempt that reached the server fences every older
      // generation before its INSERT, so a stale fence or request arriving
      // later is refused; the create below re-checks at commit time.
      // Phase 5 T3: this fence step consumes the fence budget.
      const overFenceBudget = await enforceRateLimit(serviceClient, dbUser.id, 'message:fence');
      if (overFenceBudget) {
        return overFenceBudget;
      }
      let fence;
      try {
        fence = await messageRepository.fenceClientMessage(
          { senderId: dbUser.id, conversationId: conversation.id, clientMessageId: keyed.clientMessageId },
          keyed.attempt.generation
        );
      } catch (error) {
        const refusal = createRefusal(error);
        if (refusal) {
          return refusal;
        }
        throw error;
      }
      if (fence.outcome === 'superseded') {
        return attemptSupersededResponse();
      }
      if (fence.outcome === 'stored' && fence.messageId === null) {
        // Delivered under this key and deleted since: never recreate it.
        return messageDeletedResponse();
      }
    }

    if (attachmentIds.value) {
      return await createWithAttachments(
        serviceClient,
        messageRepository,
        conversationRepository,
        new SupabaseMessageAttachmentUploadRepository(serviceClient),
        baseMessageData,
        attachmentIds.value,
        keyed
      );
    }

    const messageData: MessageCreateData = { ...baseMessageData, type: safeType };

    if (!keyed) {
      // Unkeyed text create (published client): created by the transactional
      // create function, which charges the insertion quota only when the
      // insertion commits (Phase 5 T3). Same legacy response.
      let createdMessage: Message;
      try {
        createdMessage = await messageRepository.createUnkeyed(messageData, MESSAGE_INSERTION_QUOTA);
      } catch (error) {
        const refusal = createRefusal(error);
        if (refusal) {
          return refusal;
        }
        throw error;
      }
      await touchConversation(conversationRepository, conversation.id);
      return NextResponse.json({ message: createdMessage }, { status: 201 });
    }

    let outcome;
    try {
      outcome = await messageRepository.createWithClientKey(
        messageData,
        keyed.clientMessageId,
        keyed.attempt,
        MESSAGE_INSERTION_QUOTA
      );
    } catch (error) {
      const refusal = createRefusal(error);
      if (refusal) {
        return refusal;
      }
      throw error;
    }
    if (!outcome.created) {
      // A retry of a composition whose create already committed (e.g. its
      // response was lost): answer with the stored message, insert nothing.
      // The key is per composition, so a different payload — including a
      // stored message that carries attachments — is a client bug.
      const stored = (await messageRepository.findById(outcome.message.id)) ?? outcome.message;
      const linkedIds = await new SupabaseMessageAttachmentUploadRepository(serviceClient).listLinkedAttachmentIds(stored.id);
      if (!isSameComposition(outcome.storedComposition, stored, linkedIds, keyed.attempt.composition)) {
        return clientKeyReused();
      }
      return messageResponse(stored, 200, keyed);
    }

    await touchConversation(conversationRepository, conversation.id);

    return messageResponse(outcome.message, 201, keyed);
  } catch (error) {
    console.error('Error creating message:', error);
    return jsonError(500, 'INTERNAL_ERROR', 'Failed to create message');
  }
}
